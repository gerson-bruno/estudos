// Math é uma funcao nativa do JS que possui varias funcoes matematicas que podem ser usadas de forma facil.

console.log(Math.max(5, 2, 10)); // retorna o maior valor
console.log(Math.min(5, 2, 10)); // retorna o menor valor
console.log(Math.floor(5.5)); // arredonda para baixo
console.log(Math.ceil(5.5)); // arredonda para cima
console.log(Math.round(5.5)); // arredonda para o inteiro mais prático