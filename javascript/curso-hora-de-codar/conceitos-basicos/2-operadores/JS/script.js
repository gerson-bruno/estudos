// 1 - Number
console.log(typeof 2);
console.log(typeof 2.2);
console.log(typeof -4);

// 2 - Ops. aritméticas
console.log(2 + 4);
console.log(10 - 5);
console.log(5 * 4);
console.log(10 / 2);
console.log(5 + (3 * 4));
console.log((5 + 3) * 4);
console.log(5 + 3 * 4);

// 3 - Special Numbers
console.log(typeof Infinity);
console.log(typeof -Infinity);
console.log(12 * "asd"); // Retorna NaN porque não é um número.
console.log(typeof NaN); // Not a Number - Resulta em um number que não representa um número.

// 4 - Strings
console.log("Um texto");
console.log(`Mais um texto`);
console.log(typeof "Opa");
console.log(typeof `Mais um texto`);
console.log(typeof "4");

// 5 - Símbolos especiais em string (\n, \t) - Não são comumente usados.
console.log("Testando \nquebra de linha");
console.log("Espaçamento \tde tab");
